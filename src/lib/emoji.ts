/** Flat list, de-duplicated, for the default browse view. */
export const ALL_EMOJIS: string[] = [
  ...new Set(EMOJI_GROUPS.flatMap((g) => g.items.map(([e]) => e))),
]

export function searchEmojis(query: string): string[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  const hits: string[] = []
  for (const g of EMOJI_GROUPS) {
    const groupHit = g.name.includes(q)
    for (const [emoji, keywords] of g.items) {
      if (groupHit || keywords.toLowerCase().includes(q) || emoji === q) hits.push(emoji)
    }
  }
  return [...new Set(hits)]
}
